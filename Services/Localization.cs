        public static void SetLanguage(string lang)
        {
            CurrentLanguage = string.Equals(lang, "en", StringComparison.OrdinalIgnoreCase) ? "en" : "ru";
        }

        private static Dictionary<string, string> ActiveDict => CurrentLanguage == "en" ? En : Ru;

        public static string Get(string key)
        {
            if (ActiveDict.TryGetValue(key, out var value))
                return value;

            return Ru.TryGetValue(key, out var fallback) ? fallback : key;
        }

        public static string Get(string key, params object[] args) => string.Format(Get(key), args);

        // Переписывает все ключи в ресурсах приложения — все {DynamicResource KEY}
        // привязки в XAML сразу подхватят новые строки, точно так же как при смене темы.
        public static void ApplyToResources(Application app)
        {
            foreach (var kv in Ru)
            {
                app.Resources[kv.Key] = Get(kv.Key);
            }
        }
